for f in glob.glob(R + '/notes/*.json'):
    ws = json.load(open(f)); changed = False
    for w in ws:
        for field, old, new in E.get(w['n'], []):
            if field == 'body':
                hits = [i for i, p in enumerate(w['body_ko']) if old in p]
                if not hits:
                    assert any(new in p for p in w['body_ko']), (w['n'], old)  # 이미 적용됨(재실행)
                    continue
                w['body_ko'][hits[0]] = w['body_ko'][hits[0]].replace(old, new)
            else:
                k = field.split(':')[1]
                row = next(r for r in w['meta_ko'] if r[0] == k); row[1] = new
            changed = True
    if changed: json.dump(ws, open(f, 'w'), ensure_ascii=False, indent=2)
